import type { Confidence, HarnessId, Observation, Session, SessionMetrics } from "@/mock/types";

const obs = (value: number | null, confidence: Confidence, source?: string, note?: string): Observation<number> => ({
  value: confidence === "unavailable" ? null : value,
  confidence,
  source,
  note,
});

interface RawMetrics {
  durationMin: number;
  input: number;
  output: number;
  cache: number;
  cost: number;
  modelCalls: number;
  toolCalls: number;
  errors: number;
  permissions: number;
  systemPrompt: number;
}

/**
 * What each harness actually exposes differs; the confidence pattern reflects that,
 * so the UI is tested against realistic gaps (CDC §17).
 */
export function metricsFor(harnessId: HarnessId, m: RawMetrics): SessionMetrics {
  const duration = obs(m.durationMin * 60_000, "observed", "horloge Warden");
  const toolCalls = obs(m.toolCalls, "observed", "ACP tool_call");
  const errors = obs(m.errors, "observed", "ACP tool_call status=failed");
  const permissions = obs(m.permissions, "observed", "ACP session/request_permission");
  switch (harnessId) {
    case "opencode":
      return {
        durationMs: duration,
        inputTokens: obs(m.input, "observed", "ACP usage (total par tour)"),
        outputTokens: obs(m.output, "observed", "ACP usage (total par tour)"),
        cacheReadTokens: obs(null, "unavailable", undefined, "Non exposé par OpenCode via ACP"),
        cost: obs(m.cost, "estimated", "tokens × catalogue de prix"),
        modelCalls: obs(m.modelCalls, "inferred", "déduit des messages agent"),
        toolCalls,
        errors,
        permissionsRequested: permissions,
        systemPromptTokens: obs(null, "unavailable", undefined, "Prompt système non exposé"),
      };
    case "claude-code":
      return {
        durationMs: duration,
        inputTokens: obs(m.input, "observed", "Agent SDK usage"),
        outputTokens: obs(m.output, "observed", "Agent SDK usage"),
        cacheReadTokens: obs(m.cache, "observed", "Agent SDK usage"),
        cost: obs(m.cost, "observed", "Agent SDK total_cost_usd"),
        modelCalls: obs(m.modelCalls, "observed", "Agent SDK messages"),
        toolCalls,
        errors,
        permissionsRequested: permissions,
        systemPromptTokens: obs(m.systemPrompt, "estimated", "cache_creation du 1er appel"),
      };
    case "codex":
      return {
        durationMs: duration,
        inputTokens: obs(m.input, "observed", "codex-acp token_count"),
        outputTokens: obs(m.output, "observed", "codex-acp token_count"),
        cacheReadTokens: obs(m.cache, "observed", "codex-acp token_count"),
        cost: obs(m.cost, "estimated", "tokens × catalogue de prix"),
        modelCalls: obs(m.modelCalls, "inferred", "déduit des tours"),
        toolCalls,
        errors,
        permissionsRequested: permissions,
        systemPromptTokens: obs(null, "unavailable"),
      };
    case "pi":
    case "omp":
      return {
        durationMs: duration,
        inputTokens: obs(m.input, "observed", "usage par message"),
        outputTokens: obs(m.output, "observed", "usage par message"),
        cacheReadTokens: obs(m.cache, "observed", "usage par message"),
        cost: obs(m.cost, "observed", "coût par message"),
        modelCalls: obs(m.modelCalls, "observed"),
        toolCalls,
        errors,
        permissionsRequested: permissions,
        systemPromptTokens: obs(m.systemPrompt, "observed", "prompt système exporté"),
      };
  }
}

